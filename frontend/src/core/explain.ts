/** شرح رسم لغير المتخصصين: يظهر بزر «؟» بدل الرسم، ويعود الرسم بزر العودة. */
export interface Explanation {
  /** ما معنى القياس نفسه (جملتان بلغة يومية) */
  meaning: string;
  /** ماذا يوضح هذا الرسم تحديدًا (الخطوط، الوحدة، التردد) */
  shows: string;
  /** كيف تقرأه: نقاط قصيرة (ماذا يعني الصعود، الفجوة، المقارنة…) */
  read: string[];
  /** لماذا يهمّ صانع القرار والمواطن */
  why: string;
  /** مصطلحات قد لا يعرفها القارئ */
  terms?: { term: string; definition: string }[];
  /** تنبيهات: حدود البيانات، سوء الفهم الشائع */
  caution?: string;
}
